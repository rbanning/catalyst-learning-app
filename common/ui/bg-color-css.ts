import { opacitySwitch, intensitySwitch } from "./css-utils";
import { ThemeColorFullWithTransparent, ThemeColorIntensity, ThemeColorOpacity } from "../styles";

export function bgColorCss(color: ThemeColorFullWithTransparent, intensity?: ThemeColorIntensity, opacity?: ThemeColorOpacity) {
  intensity ??= 'DEFAULT';
  opacity ??= 'full';

  switch(color) {
    case 'black':
      return opacitySwitch(opacity,
        intensitySwitch(intensity,
          'bg-slate-900',
          'bg-slate-400',
          'bg-black'),
        intensitySwitch(intensity,
          'bg-slate-900/75',
          'bg-slate-400/75',
          'bg-black/75'),
        intensitySwitch(intensity,
          'bg-slate-900/50',
          'bg-slate-400/50',
          'bg-black/50'),
        intensitySwitch(intensity,
          'bg-slate-900/25',
          'bg-slate-400/25',
          'bg-black/25'),
        intensitySwitch(intensity,
          'bg-slate-900/10',
          'bg-slate-400/10',
          'bg-black/10'));
    case 'white':
      return opacitySwitch(opacity,
        intensitySwitch(intensity,
          'bg-white',
          'bg-white',
          'bg-slate-50'),
        intensitySwitch(intensity,
          'bg-white/75',
          'bg-white/75',
          'bg-slate-50/75'),
        intensitySwitch(intensity,
          'bg-white/50',
          'bg-white/50',
          'bg-slate-50/50'),
        intensitySwitch(intensity,
          'bg-white/25',
          'bg-white/25',
          'bg-slate-50/25'),
        intensitySwitch(intensity,
          'bg-white/10',
          'bg-white/10',
          'bg-slate-50/10'));            
    case 'surface':
      return opacitySwitch(opacity,
        intensitySwitch(intensity,
          'bg-hallpass-surface',
          'bg-hallpass-surface-light',
          'bg-hallpass-surface-dark'),
        intensitySwitch(intensity,
          'bg-hallpass-surface/75',
          'bg-hallpass-surface-light/75',
          'bg-hallpass-surface-dark/75'),
        intensitySwitch(intensity,
          'bg-hallpass-surface/50',
          'bg-hallpass-surface-light/50',
          'bg-hallpass-surface-dark/50'),
        intensitySwitch(intensity,
          'bg-hallpass-surface/25',
          'bg-hallpass-surface-light/25',
          'bg-hallpass-surface-dark/25'),
        intensitySwitch(intensity,
          'bg-hallpass-surface/10',
          'bg-hallpass-surface-light/10',
          'bg-hallpass-surface-dark/10'));
    case 'background':
      return opacitySwitch(opacity,
        intensitySwitch(intensity, 
          'bg-hallpass-background',
          'bg-hallpass-background/90',
          'bg-slate-50'),
        intensitySwitch(intensity, 
          'bg-hallpass-background/75',
          'bg-hallpass-background/60',
          'bg-slate-50/75'),
        intensitySwitch(intensity, 
          'bg-hallpass-background/50',
          'bg-hallpass-background/40',
          'bg-slate-50/50'),
        intensitySwitch(intensity, 
          'bg-hallpass-background/25',
          'bg-hallpass-background/20',
          'bg-slate-50/25'),
        intensitySwitch(intensity, 
          'bg-hallpass-background/10',
          'bg-hallpass-background/5',
          'bg-slate-50/10'),
          );
    case 'transparent':
      return 'bg-transparent'
    case 'neutral':
      return opacitySwitch(opacity, 
        intensitySwitch(intensity,
          'bg-hallpass-neutral',
          'bg-hallpass-neutral-light',
          'bg-hallpass-neutral-dark'),
        intensitySwitch(intensity,
          'bg-hallpass-neutral/75',
          'bg-hallpass-neutral-light/75',
          'bg-hallpass-neutral-dark/75'),
        intensitySwitch(intensity,
          'bg-hallpass-neutral/50',
          'bg-hallpass-neutral-light/50',
          'bg-hallpass-neutral-dark/50'),
        intensitySwitch(intensity,
          'bg-hallpass-neutral/25',
          'bg-hallpass-neutral-light/25',
          'bg-hallpass-neutral-dark/25'),
        intensitySwitch(intensity,
          'bg-hallpass-neutral/10',
          'bg-hallpass-neutral-light/10',
          'bg-hallpass-neutral-dark/10'));
    case 'primary':
      return opacitySwitch(opacity, 
        intensitySwitch(intensity,
          'bg-hallpass-primary',
          'bg-hallpass-primary-light',
          'bg-hallpass-primary-dark'),
        intensitySwitch(intensity,
          'bg-hallpass-primary/75',
          'bg-hallpass-primary-light/75',
          'bg-hallpass-primary-dark/75'),
        intensitySwitch(intensity,
          'bg-hallpass-primary/50',
          'bg-hallpass-primary-light/50',
          'bg-hallpass-primary-dark/50'),
        intensitySwitch(intensity,
          'bg-hallpass-primary/25',
          'bg-hallpass-primary-light/25',
          'bg-hallpass-primary-dark/25'),
        intensitySwitch(intensity,
          'bg-hallpass-primary/10',
          'bg-hallpass-primary-light/10',
          'bg-hallpass-primary-dark/10'));
    case 'secondary':
      return opacitySwitch(opacity, 
        intensitySwitch(intensity,
          'bg-hallpass-secondary',
          'bg-hallpass-secondary-light',
          'bg-hallpass-secondary-dark'),
        intensitySwitch(intensity,
          'bg-hallpass-secondary/75',
          'bg-hallpass-secondary-light/75',
          'bg-hallpass-secondary-dark/75'),
        intensitySwitch(intensity,
          'bg-hallpass-secondary/50',
          'bg-hallpass-secondary-light/50',
          'bg-hallpass-secondary-dark/50'),
        intensitySwitch(intensity,
          'bg-hallpass-secondary/25',
          'bg-hallpass-secondary-light/25',
          'bg-hallpass-secondary-dark/25'),
        intensitySwitch(intensity,
          'bg-hallpass-secondary/10',
          'bg-hallpass-secondary-light/10',
          'bg-hallpass-secondary-dark/10'));
    case 'error':
      return opacitySwitch(opacity, 
        intensitySwitch(intensity,
          'bg-hallpass-error',
          'bg-hallpass-error-light',
          'bg-hallpass-error-dark'),
        intensitySwitch(intensity,
          'bg-hallpass-error/75',
          'bg-hallpass-error-light/75',
          'bg-hallpass-error-dark/75'),
        intensitySwitch(intensity,
          'bg-hallpass-error/50',
          'bg-hallpass-error-light/50',
          'bg-hallpass-error-dark/50'),
        intensitySwitch(intensity,
          'bg-hallpass-error/25',
          'bg-hallpass-error-light/25',
          'bg-hallpass-error-dark/25'),
        intensitySwitch(intensity,
          'bg-hallpass-error/10',
          'bg-hallpass-error-light/10',
          'bg-hallpass-error-dark/10'));        
    default:
      throw new Error(`Unsupported background color: ${color}`);
  }
}

